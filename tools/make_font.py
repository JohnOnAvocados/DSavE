#!/usr/bin/env python3
"""Render the UI fonts into C source.

DSavE draws text with antialiased bitmap fonts made from DejaVu Sans (see
source/ui/fonts/LICENSE-DejaVu.txt). This script turns the TTFs into 4-bit
alpha glyphs in source/ui/font_data.c. Run it again only to change the fonts:

    python3 tools/make_font.py [path/to/DejaVuSans.ttf path/to/DejaVuSans-Bold.ttf]

Needs Pillow.
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "source", "ui", "font_data.c")

DEFAULT_DIR = "/usr/share/fonts/truetype/dejavu"
REGULAR = os.path.join(DEFAULT_DIR, "DejaVuSans.ttf")
BOLD = os.path.join(DEFAULT_DIR, "DejaVuSans-Bold.ttf")

# (C name, which TTF, pixel size)
FONTS = [
    ("font_small", "regular", 10),
    ("font_body", "regular", 12),
    ("font_bold", "bold", 12),
    ("font_title", "bold", 15),
]

# ASCII, Latin-1 (European game titles), and the symbols the UI uses.
CODEPOINTS = (
    list(range(0x20, 0x7F))
    + list(range(0xA0, 0x100))
    + [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2122, 0x2190, 0x2191, 0x2192, 0x2193,
       0x21C4, 0x2260, 0x232B, 0x25B2, 0x25BC, 0x25CB, 0x25CF, 0x2605,
       0x2713, 0x2715]
)


def has_glyph(font, cp):
    # Pillow draws missing glyphs as the font's .notdef box; compare masks.
    if cp < 0x100:
        return True
    def img(ch):
        im = Image.new("L", (64, 64), 0)
        ImageDraw.Draw(im).text((8, 8), ch, font=font, fill=255)
        return im.tobytes()
    return img(chr(cp)) != img("\uffff")


def render(name, path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs = []
    data = bytearray()
    for cp in CODEPOINTS:
        if not has_glyph(font, cp):
            print(f"{name}: no glyph for U+{cp:04X}, skipped", file=sys.stderr)
            continue
        ch = chr(cp)
        advance = round(font.getlength(ch))
        box = font.getbbox(ch)  # Relative to the line's top-left (ascender)
        x0, y0, x1, y1 = box
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        offset = len(data)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
            px = list(img.tobytes())
            # 4-bit alpha, two pixels per byte, low nibble first, rows padded.
            for row in range(h):
                line = px[row * w:(row + 1) * w]
                if w % 2:
                    line.append(0)
                for i in range(0, len(line), 2):
                    a = (line[i] + 8) // 17
                    b = (line[i + 1] + 8) // 17
                    data.append(a | (b << 4))
        glyphs.append((cp, w, h, x0, y0, advance, offset))
    return ascent, descent, glyphs, data


def main():
    paths = {"regular": REGULAR, "bold": BOLD}
    if len(sys.argv) == 3:
        paths = {"regular": sys.argv[1], "bold": sys.argv[2]}

    out = ["// Generated by tools/make_font.py from DejaVu Sans; do not edit.",
           "// Font license: source/ui/fonts/LICENSE-DejaVu.txt", "",
           '#include "gfx.h"', ""]
    for name, which, size in FONTS:
        ascent, descent, glyphs, data = render(name, paths[which], size)
        out.append(f"static const uint8_t {name}_bits[{max(1, len(data))}] = {{")
        for i in range(0, len(data), 16):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
        out.append("};")
        out.append(f"static const Glyph {name}_glyphs[{len(glyphs)}] = {{")
        for cp, w, h, x0, y0, adv, off in glyphs:
            out.append(f"    {{ 0x{cp:04x}, {w}, {h}, {x0}, {y0}, {adv}, {off} }},")
        out.append("};")
        out.append(f"const Font {name} = {{ {ascent + descent}, {ascent}, {len(glyphs)}, "
                   f"{name}_glyphs, {name}_bits }};")
        out.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(out))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
